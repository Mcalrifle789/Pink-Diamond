console.log('toast:', await page.locator('.toast').innerText().catch(() => ''));
console.log('iframes:', await page.evaluate(() => document.querySelectorAll('#checkout-mount iframe').length));
console.log('errors:', errors.join(' | ').slice(0, 400));
await page.screenshot({ path: 'C:/Users/hextu/head-coding-agent/shots/checkout-sub-debug.png' });
